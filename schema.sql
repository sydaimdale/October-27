-- Class roster survey schema
-- Normalized from class_dataset.csv (one response per student today;
-- survey_responses is separate so a student can submit again later).

CREATE TABLE students (
    student_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    netid        TEXT NOT NULL UNIQUE,
    full_name    TEXT NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE survey_responses (
    response_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id             INTEGER NOT NULL REFERENCES students (student_id) ON DELETE CASCADE,
    school_year            TEXT NOT NULL CHECK (school_year IN ('Freshman', 'Sophomore', 'Junior', 'Senior')),
    intro_programming      TEXT NOT NULL CHECK (intro_programming IN ('took_it', 'equivalent', 'neither')),
    skill_programming      SMALLINT NOT NULL CHECK (skill_programming BETWEEN 1 AND 5),
    skill_data_stats       SMALLINT NOT NULL CHECK (skill_data_stats BETWEEN 1 AND 5),
    skill_frontend_design  SMALLINT NOT NULL CHECK (skill_frontend_design BETWEEN 1 AND 5),
    skill_business_pitch   SMALLINT NOT NULL CHECK (skill_business_pitch BETWEEN 1 AND 5),
    working_style          TEXT,
    interests              TEXT,
    semester_goal          TEXT,
    submitted_at           TIMESTAMPTZ NOT NULL,
    UNIQUE (student_id, submitted_at)
);

CREATE INDEX idx_survey_responses_student ON survey_responses (student_id);

-- Lookup: Python, SQL, JavaScript, Excel, R, none yet, ...
CREATE TABLE tools (
    tool_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     TEXT NOT NULL UNIQUE
);

-- Lookup: Weekday mornings, Weekday afternoons, ...
CREATE TABLE availability_slots (
    slot_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label       TEXT NOT NULL UNIQUE,
    day_part    TEXT NOT NULL CHECK (day_part IN ('weekday', 'weekend')),
    time_of_day TEXT NOT NULL CHECK (time_of_day IN ('mornings', 'afternoons', 'evenings'))
);

CREATE TABLE response_tools (
    response_id INTEGER NOT NULL REFERENCES survey_responses (response_id) ON DELETE CASCADE,
    tool_id     INTEGER NOT NULL REFERENCES tools (tool_id) ON DELETE RESTRICT,
    PRIMARY KEY (response_id, tool_id)
);

CREATE TABLE response_availability (
    response_id INTEGER NOT NULL REFERENCES survey_responses (response_id) ON DELETE CASCADE,
    slot_id     INTEGER NOT NULL REFERENCES availability_slots (slot_id) ON DELETE RESTRICT,
    PRIMARY KEY (response_id, slot_id)
);

